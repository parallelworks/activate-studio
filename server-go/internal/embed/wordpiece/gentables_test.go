package wordpiece

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
	"testing"
	"unicode"
)

// TestWriteTables writes tables.go from the library's per code point
// behaviour (WORDPIECE_WRITE_TABLES=1 with WORDPIECE_CP_GOLDEN and
// WORDPIECE_TOKENIZER set): for each code point where Go's tables give
// another answer, the smallest set of overrides that gives the library's.
func TestWriteTables(t *testing.T) {
	if os.Getenv("WORDPIECE_WRITE_TABLES") != "1" {
		t.Skip("WORDPIECE_WRITE_TABLES not set")
	}
	tok, err := Load(os.Getenv("WORDPIECE_TOKENIZER"))
	if err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(os.Getenv("WORDPIECE_CP_GOLDEN"))
	if err != nil {
		t.Fatal(err)
	}
	var raw map[string][2]any
	if err := json.Unmarshal(b, &raw); err != nil {
		t.Fatal(err)
	}
	want := map[rune][2]any{}
	for k, v := range raw {
		n, _ := strconv.Atoi(k)
		want[rune(n)] = v
	}
	otherOverride, punctOverride, markOverride, lowerOverride, keepWhole = map[rune]bool{}, map[rune]bool{}, map[rune]bool{}, map[rune]string{}, map[rune]bool{}
	class := func(ch string) float64 {
		p := tok.preTokenize("a" + ch + "a")
		if len(p) == 3 && p[1] == ch {
			return 1
		} else if len(p) == 2 {
			return 2
		}
		return 0
	}
	var unsolved []string
	for cp := rune(0x80); cp < 0x110000; cp++ {
		if cp >= 0xD800 && cp <= 0xDFFF {
			continue
		}
		ch := string(cp)
		wn, wc := ch, 0.0
		if v, ok := want[cp]; ok {
			wn, wc = v[0].(string), v[1].(float64)
		}
		if tok.normalize(ch) == wn && class(ch) == wc {
			continue
		}
		solved := false
		for mask := 1; mask < 32 && !solved; mask++ {
			if mask&16 != 0 {
				keepWhole[cp] = true
			}
			if mask&1 != 0 {
				markOverride[cp] = !unicode.Is(unicode.Mn, cp)
			}
			if mask&2 != 0 {
				otherOverride[cp] = !unicode.In(cp, unicode.Cc, unicode.Cf, unicode.Co, unicode.Cs)
			}
			if mask&4 != 0 {
				punctOverride[cp] = !unicode.IsPunct(cp)
			}
			if mask&8 != 0 {
				lowerOverride[cp] = wn
			}
			if tok.normalize(ch) == wn && class(ch) == wc {
				solved = true
				break
			}
			delete(markOverride, cp)
			delete(otherOverride, cp)
			delete(punctOverride, cp)
			delete(lowerOverride, cp)
			delete(keepWhole, cp)
		}
		if !solved {
			unsolved = append(unsolved, fmt.Sprintf("%U", cp))
		}
	}
	if len(unsolved) > 0 {
		t.Fatalf("no overrides give the library's answer for %v", unsolved)
	}
	var sb strings.Builder
	sb.WriteString("// Code generated by TestWriteTables from the tokenizers library; DO NOT EDIT.\n\npackage wordpiece\n\n")
	sb.WriteString("// Overrides of Go's Unicode tables where the tokenizers library's differ\n// (see the package comment).\nvar (\n")
	writeBool := func(name string, m map[rune]bool) {
		keys := make([]int, 0, len(m))
		for k := range m {
			keys = append(keys, int(k))
		}
		sort.Ints(keys)
		fmt.Fprintf(&sb, "\t%s = map[rune]bool{", name)
		for i, k := range keys {
			if i%6 == 0 {
				sb.WriteString("\n\t\t")
			} else {
				sb.WriteString(" ")
			}
			fmt.Fprintf(&sb, "0x%04X: %v,", k, m[rune(k)])
		}
		sb.WriteString("\n\t}\n")
	}
	writeBool("otherOverride", otherOverride)
	writeBool("punctOverride", punctOverride)
	writeBool("markOverride", markOverride)
	writeBool("keepWhole", keepWhole)
	keys := make([]int, 0, len(lowerOverride))
	for k := range lowerOverride {
		keys = append(keys, int(k))
	}
	sort.Ints(keys)
	sb.WriteString("\tlowerOverride = map[rune]string{")
	for _, k := range keys {
		fmt.Fprintf(&sb, "\n\t\t0x%04X: %q,", k, lowerOverride[rune(k)])
	}
	sb.WriteString("\n\t}\n)\n")
	if err := os.WriteFile("tables.go", []byte(sb.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("other %d, punct %d, mark %d, lower %d, whole %d", len(otherOverride), len(punctOverride), len(markOverride), len(lowerOverride), len(keepWhole))
}
